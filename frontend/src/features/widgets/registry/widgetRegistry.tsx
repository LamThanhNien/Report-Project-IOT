const aliasMap = new Map<string, WidgetDefinition>();
for (const definition of widgetDefinitions) {
  aliasMap.set(definition.id, definition);
  for (const legacyId of definition.legacyIds ?? []) {
    aliasMap.set(legacyId, definition);
  }
}

const fallbackDefinition = widgetDefinitions.find((item) => item.id === "text_value") ?? widgetDefinitions[0];

export function resolveWidgetDefinition(widgetType: string): WidgetDefinition {
  return aliasMap.get(widgetType) ?? fallbackDefinition;
}

export function listWidgetDefinitions(search = "", includeHidden = false): WidgetDefinition[] {
  const query = search.trim().toLowerCase();
  const items = widgetDefinitions
    .filter((definition) => {
      if (!includeHidden && definition.hidden) return false;
      if (!query) return true;
      return `${definition.label} ${definition.description} ${definition.id}`.toLowerCase().includes(query);
    })
    .sort((a, b) => a.category.localeCompare(b.category) || a.label.localeCompare(b.label));
  return items;
}

export const ALL_WIDGET_TYPE_IDS = widgetDefinitions.flatMap((definition) => [definition.id, ...(definition.legacyIds ?? [])]);
