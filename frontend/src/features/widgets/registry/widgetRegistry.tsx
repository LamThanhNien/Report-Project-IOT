function makeDefinition(definition: WidgetDefinition): WidgetDefinition {
  const id = definition.id;
  const numericControls = new Set(["slider_control", "knob_dial_control", "numeric_input", "stepper_control"]);
  const booleanControls = new Set(["toggle_switch", "push_button", "momentary_button", "schedule_button_timer"]);
  const optionControls = new Set(["dropdown_command_selector", "segmented_control"]);
  const booleanTelemetry = new Set(["led_indicator", "icon_status", "device_online_status", "boolean_status_card", "alarm_badge"]);
  const numericTelemetry = new Set([
    "number_card",
    "battery_indicator",
    "signal_strength_wifi_rssi",
    "progress_bar",
    "thermometer",
    "humidity_card",
    "circular_gauge",
    "linear_gauge",
    "multi_value_card",
    "gauge_widget",
    "threshold_alert_card",
    "ota_job_status",
  ]);

  let datastream = definition.datastream;
  if (!datastream && id === "multi_telemetry_chart") {
    datastream = { dataTypes: ["integer", "double"], directions: ["telemetry", "bidirectional"], virtualOnly: true };
  } else if (!datastream && numericControls.has(id)) {
    datastream = { dataTypes: ["integer", "double"], directions: ["command", "bidirectional"], virtualOnly: true };
  } else if (!datastream && booleanControls.has(id)) {
    datastream = { dataTypes: ["boolean"], directions: ["command", "bidirectional"] };
  } else if (!datastream && optionControls.has(id)) {
    datastream = { dataTypes: ["boolean", "integer", "double", "string"], directions: ["command", "bidirectional"], virtualOnly: true };
  } else if (!datastream && definition.category === "chart") {
    datastream = { dataTypes: ["integer", "double"], directions: ["telemetry", "bidirectional"] };
  } else if (!datastream && numericTelemetry.has(id)) {
    datastream = { dataTypes: ["integer", "double"], directions: ["telemetry", "bidirectional"] };
  } else if (!datastream && booleanTelemetry.has(id)) {
    datastream = { dataTypes: ["boolean"], directions: ["telemetry", "bidirectional"] };
  } else if (!datastream && id === "text_value") {
    datastream = { dataTypes: ["string", "integer", "double"], directions: ["telemetry", "bidirectional"] };
  } else if (!datastream && definition.category === "control") {
    datastream = { virtualOnly: true };
  }
  return datastream ? { ...definition, datastream } : definition;
}

